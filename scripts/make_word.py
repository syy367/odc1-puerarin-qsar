def borders_three_line(table):
    tbl = table._tbl
    tblPr = tbl.tblPr
    for old in tblPr.findall(qn("w:tblBorders")):
        tblPr.remove(old)
    b = OxmlElement("w:tblBorders")
    for edge, val in (("top", "single"), ("left", "none"), ("bottom", "single"),
                      ("right", "none"), ("insideH", "none"), ("insideV", "none")):
        el = OxmlElement(f"w:{edge}")
        el.set(qn("w:val"), val)
        el.set(qn("w:sz"), "12" if val == "single" else "0")
        el.set(qn("w:space"), "0")
        el.set(qn("w:color"), "000000")
        b.append(el)
    tblPr.append(b)
    for cell in table.rows[0].cells:
        tcPr = cell._tc.get_or_add_tcPr()
        tb = OxmlElement("w:tcBorders")
        bt = OxmlElement("w:bottom")
        bt.set(qn("w:val"), "single")
        bt.set(qn("w:sz"), "8")
        bt.set(qn("w:space"), "0")
        bt.set(qn("w:color"), "000000")
        tb.append(bt)
        tcPr.append(tb)


def caption(text):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(12)
    p.paragraph_format.space_after = Pt(6)
    r = p.add_run(text)
    r.bold = True
    r.font.size = Pt(10)
    r.font.name = "Times New Roman"
    return p


def note(text):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(3)
    p.paragraph_format.space_after = Pt(14)
    r = p.add_run(text)
    r.font.size = Pt(8)
    r.italic = False
    return p


def make_table(df, widths=None, fs=8, align_right_from=1):
    t = doc.add_table(rows=1, cols=len(df.columns))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = True
    hdr = t.rows[0].cells
    for i, c in enumerate(df.columns):
        hdr[i].text = ""
        p = hdr[i].paragraphs[0]
        r = p.add_run(str(c))
        r.bold = True
        r.font.size = Pt(fs)
        r.font.name = "Times New Roman"
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    for _, row in df.iterrows():
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = ""
            p = cells[i].paragraphs[0]
            r = p.add_run("" if pd.isna(v) else str(v))
            r.font.size = Pt(fs)
            r.font.name = "Times New Roman"
            if i >= align_right_from and isinstance(v, (int, float)):
                p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    if widths:
        for i, w in enumerate(widths):
            for row in t.rows:
                row.cells[i].width = Cm(w)
    borders_three_line(t)
    return t


